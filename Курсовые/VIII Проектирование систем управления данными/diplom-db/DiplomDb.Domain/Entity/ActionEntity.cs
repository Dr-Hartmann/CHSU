namespace DiplomDb.Domain.Entity;

/// <summary>
/// Действие (Action) - основная бизнес-сущность, представляющая действие в сценарии.
///
/// Назначение файла:
///   - Определение доменной сущности ActionEntity в слое Domain
///   - Описание структуры данных и бизнес-логики создания действий
///   - Установление отношений с другими сущностями (один-ко-многим с StepEntity)
///
/// Используемые паттерны и приёмы:
///   1. Наследование от BaseEntity - реализация общих полей (Id, CreatedAt, UpdatedAt, IsDeleted)
///   2. Приватный конструктор - обеспечение инкапсуляции и контроля создания через фабричный метод
///   3. Фабричный метод Create() - централизованная валидация и создание экземпляров
///   4. Приватные сеттеры свойств - защита инвариантов домена от внешнего изменения
///   5. Коллекция Steps - навигационное свойство для отношения один-ко-многим
///
/// Архитектурный слой: Domain (Бизнес-логика)
/// Ответственный агент: Domain Agent
/// </summary>
public class ActionEntity : BaseEntity
{
    /// <summary>
    /// Название действия. Обязательное поле с максимальной длиной 255 символов.
    /// Использует приватный сеттер для защиты инвариантов домена.
    /// </summary>
    public string Name { get; private set; } = null!;

    /// <summary>
    /// Коллекция шагов (StepEntity), связанных с данным действием.
    /// Отношение один-ко-многим: одно действие может иметь множество шагов.
    /// Навигационное свойство для EF Core.
    /// </summary>
    public ICollection<StepEntity> Steps { get; private set; } = [];

    /// <summary>
    /// Фабричный метод для создания экземпляра ActionEntity.
    /// Обеспечивает централизованную валидацию и инкапсуляцию логики создания.
    ///
    /// Паттерн: Фабричный метод (Factory Method)
    /// Преимущества:
    ///   - Единая точка валидации входных данных
    ///   - Контроль над процессом создания объекта
    ///   - Возможность расширения без изменения клиентского кода
    /// </summary>
    /// <param name="name">Название действия. Не может быть null, пустым или состоять только из пробелов.</param>
    /// <returns>Новый экземпляр ActionEntity с заданным именем.</returns>
    /// <exception cref="ArgumentException">Выбрасывается если name является null, пустым или состоит только из пробелов.</exception>
    public static ActionEntity Create(string name)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(name);

        return new()
        {
            Name = name
        };
    }

    /// <summary>
    /// Приватный конструктор для обеспечения инкапсуляции.
    /// Требуется EF Core для создания прокси-объектов и загрузки из базы данных.
    /// Предотвращает прямое создание экземпляров через new, вынуждая использовать фабричный метод Create().
    /// </summary>
    private ActionEntity() { }
}
